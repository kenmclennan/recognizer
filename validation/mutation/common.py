ROOT = Path(__file__).resolve().parents[2]
IGNORED = shutil.ignore_patterns(
    ".git", "node_modules", ".venv", "__pycache__", ".recognizer", "target"
)
BOOLEANS = {"True": "False", "False": "True", "true": "false", "false": "true"}
OPERATOR_SET = set(SWAPS) | set(BOOLEANS) | {"not"}


def copy_repository(repository: Path, destination: Path) -> None:
    shutil.copytree(repository, destination, ignore=IGNORED)


def functions_with_sites(repository: Path, file: str) -> list[dict]:
    grammar = grammar_for(file)
    source = (repository / file).read_bytes()
    root = parse(grammar, source).root_node
    found = find_functions(root, grammar)
    spans = [
        (
            f.node.start_byte,
            f.node.end_byte,
            f.qualified,
            f.node.start_point[0] + 1,
            f.node.end_point[0] + 1,
        )
        for f in found
    ]
    rows = []

    for site in find_sites(root, grammar):
        owners = [s for s in spans if s[0] <= site.start_byte < s[1]]

        if not owners:
            continue

        owner = min(owners, key=lambda s: s[1] - s[0])
        rows.append(
            {
                "function": owner[2],
                "function_start": owner[3],
                "line": site.line,
                "operator": site.operator,
                "replacement": site.replacement,
            }
        )

    return rows


def sensor_run(
    repository: Path, file: str, language: str, command: list[str], coverage_text: str, work: Path
) -> dict:
    root = work / "sensor"
    copy_repository(repository, root)
    (root / "validation-coverage.info").write_text(coverage_text)
    cache = root / ".recognizer" / "cache"
    cache.mkdir(parents=True, exist_ok=True)
    (cache / f"scan.{language}.json").write_text(
        json.dumps(
            {
                "files": [{"path": file, "hash": "0" * 64}],
                "modules": [{"id": file}],
                "modified": False,
            }
        )
    )
    env = {
        "GIT_AUTHOR_NAME": "v",
        "GIT_AUTHOR_EMAIL": "v@example.com",
        "GIT_COMMITTER_NAME": "v",
        "GIT_COMMITTER_EMAIL": "v@example.com",
        "PATH": "/usr/bin:/bin:/usr/local/bin:/opt/homebrew/bin",
    }

    for args in (["init", "-q"], ["add", "-A", "."], ["commit", "-q", "-m", "x"]):
        subprocess.run(["git", "-C", str(root), *args], check=True, env=env, capture_output=True)

    code = sensors_main(
        [
            "mutation",
            "--repository",
            str(root),
            "--output",
            str(work / "findings.json"),
            "--settings",
            json.dumps(
                {"test_command": command, "coverage": "validation-coverage.info", "max_workers": 2}
            ),
        ]
    )

    if code != 0:
        raise SystemExit(f"the mutation sensor exited {code}")

    survivors = json.loads((root / ".recognizer/cache/mutation/survivors.json").read_text())
    overlay = json.loads((root / ".recognizer/cache/overlays/mutation.json").read_text())

    return {"survivors": survivors, "overlay": overlay}


def token_edit(old: str, new: str) -> tuple[str, str] | None:
    def pieces(text):
        return re.findall(r"\w+|[^\w\s]+|\s+", text)

    a, b = pieces(old), pieces(new)
    changes = [
        op
        for op in difflib.SequenceMatcher(a=a, b=b, autojunk=False).get_opcodes()
        if op[0] != "equal"
    ]

    if len(changes) != 1:
        return None

    _, i1, i2, j1, j2 = changes[0]

    return "".join(a[i1:i2]).strip(), "".join(b[j1:j2]).strip()


def bucket(edit: tuple[str, str] | None, line: int, sites: list[dict]) -> str:
    if edit is None:
        return "outside by design (not a single-token edit)"

    original, replacement = edit

    for site in sites:
        if (
            site["line"] == line
            and site["operator"] == original
            and site["replacement"] == replacement
        ):
            return "matched"

    if original in OPERATOR_SET:
        return "inside the operator set but not generated by the sensor"

    return "outside by design"


def emit(payload: dict) -> None:
    json.dump(payload, sys.stdout, indent=1)
