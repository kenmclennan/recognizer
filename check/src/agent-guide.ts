export function agentGuide(commands: Command[] = COMMANDS): string {
  return [
    "The Recognizer guide for agents",
    "",
    "Commands:",
    ...commands.map(
      (command) => `recognizer ${command.name} - ${command.summary}`,
    ),
    "",
    ...RULES,
    "",
    ...RECIPES,
    "",
  ].join("\n");
}
