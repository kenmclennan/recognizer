import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, "../../app");
const rustSource = join(app, "src-tauri", "src");

function rustFiles(directory: string): string[] {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);

    return entry.isDirectory()
      ? rustFiles(path)
      : path.endsWith(".rs")
        ? [path]
        : [];
  });
}

function trackedFiles(...paths: string[]): string[] {
  return execFileSync(
    "git",
    ["ls-files", "--cached", "--others", "--exclude-standard", "--", ...paths],
    { cwd: app, encoding: "utf8" },
  )
    .split("\n")
    .filter((line) => line !== "")
    .map((line) => resolve(app, line))
    .filter((file) => existsSync(file));
}

function linesMatching(files: string[], pattern: RegExp): string[] {
  return files.flatMap((file) =>
    readFileSync(file, "utf8")
      .split("\n")
      .filter((line) => pattern.test(line))
      .map((line) => `${file}: ${line.trim()}`),
  );
}

const SCAN_RUN_PATTERN = new RegExp(
  [
    "scan-running",
    "fn run_with",
    "fn spawn_and_stream",
    "fn check_modules",
    "fn check_suites",
    "fn check_names",
    "fn answer_describe",
    "fn write_structure",
    "fn sensor_name_ok",
    "fn scan_args",
    "fn scan_flags",
    "fn live_run",
    "fn read_run\\(",
    "fn refusal_text",
    "fn appended_lines",
    "fn stop_record",
    "fn attached_app_runs",
    "fn stop_attached",
    "fn stop_scan_for",
    "fn planned_work",
    "fn work_args",
    "fn work_file",
  ].join("|"),
);

const REMOVED_COMMANDS = new RegExp(
  `\\b(${[
    "run_scan",
    "stop_scan",
    "answer_describe",
    "watch_external_scan",
    "write_structure",
    "fn planned_work",
    "invoke\\(\\s*[\"']planned_work",
    "allow-run-scan",
    "allow-stop-scan",
    "allow-answer-describe",
    "allow-watch-external-scan",
    "allow-write-structure",
    "allow-planned-work",
  ].join("|")})\\b`,
);

const PLANNING_NAMES = new RegExp(
  `\\b(${[
    "planFor",
    "sensorFreshness",
    "staleModules",
    "gapOf",
    "describeGap",
    "freshnessScope",
    "modulesWithFunctions",
    "tickedPhases",
    "suitesForSense",
    "workOf",
  ].join("|")})\\b`,
);

const PLANNER_NAMES = /\b(createPlanner|planThrough|planReads)\b/;

const ANALYSIS_NAMES = /\b(structureSensor|writeStructure|write_structure)\b/;

describe("the app holds no scan-run logic", () => {
  it("the_scan_run_functions_are_gone", () => {
    const files = rustFiles(rustSource);

    expect(files.length).toBeGreaterThan(0);
    expect(files.some((file) => file.endsWith("core_client.rs"))).toBe(true);
    expect(linesMatching(files, SCAN_RUN_PATTERN)).toEqual([]);
  });

  it("the_removed_commands_are_gone_everywhere", () => {
    const files = trackedFiles("src-tauri", "src");

    expect(files.length).toBeGreaterThan(0);
    expect(linesMatching(files, REMOVED_COMMANDS)).toEqual([]);
  });

  it("the_relay_command_is_permitted", () => {
    const build = readFileSync(join(app, "src-tauri", "build.rs"), "utf8");
    const permissions = readFileSync(
      join(app, "src-tauri", "permissions", "app.toml"),
      "utf8",
    );
    const generated = readFileSync(
      join(app, "src-tauri", "permissions", "autogenerated", "core_call.toml"),
      "utf8",
    );

    expect(build).toContain("core_call");
    expect(permissions).toContain("allow-core-call");
    expect(generated).toContain("core_call");
  });

  it("the_app_plans_only_through_the_service", () => {
    const sources = trackedFiles("src").filter((file) => file.endsWith(".ts"));

    expect(linesMatching(sources, PLANNING_NAMES)).toEqual([]);

    const planners = linesMatching(sources, PLANNER_NAMES).map(
      (line) => line.split(": ")[0] as string,
    );

    expect(
      [...new Set(planners)].map((file) => file.split("/").pop()).sort(),
    ).toEqual(["plan-reads.ts", "scan-fake.ts"]);
  });

  it("the_app_runs_no_structural_analysis", () => {
    const files = trackedFiles("src", "src-tauri");

    expect(files.length).toBeGreaterThan(0);
    expect(
      linesMatching(
        files.filter((file) => !file.includes("/gen/")),
        ANALYSIS_NAMES,
      ),
    ).toEqual([]);
  });
});
