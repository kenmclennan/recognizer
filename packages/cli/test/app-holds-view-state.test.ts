import { execFileSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");

const PARSES_JSON = [
  "packages/app/src/look-page.ts",
  "packages/app/src/panel-widths.ts",
  "packages/app/src/setup-source.ts",
  "packages/app/src/view-file.ts",
  "packages/app/src/window-fake.ts",
  "packages/app/src/window-source.ts",
];

const READS_FILES = ["packages/app/src/look-page.ts"];

const REMOVED_COMMANDS = [
  "read_scan_cache",
  "read_responsibilities",
  "read_run_records",
  "read_sensor_inputs",
  "setup_survey",
  "setup_recommend",
  "setup_apply",
  "setup_try",
  "stop_setup",
];

const LIBRARY_RULES = [
  "afterFoldToggle",
  "afterPanelOpen",
  "afterSensorTick",
  "afterSuiteTick",
  "buildFreshness",
  "changeMarks",
  "memberMarks",
  "classifyOpened",
  "responsibilityStates",
  "scanHistory",
  "estimateParts",
];

function grep(args: string[]): string[] {
  try {
    return execFileSync("git", ["grep", ...args], {
      cwd: root,
      encoding: "utf8",
    })
      .split("\n")
      .filter((line) => line !== "");
  } catch (error) {
    if ((error as { status?: number }).status === 1) {
      return [];
    }

    throw error;
  }
}

function filesMatching(pattern: string, paths: string[]): string[] {
  return grep(["-lE", pattern, "--", ...paths]).sort();
}

function outsideTests(files: string[]): string[] {
  return files.filter((file) => !file.includes("/test/"));
}

describe("the app holds only view state", () => {
  it("the_app_parses_no_document", () => {
    expect(filesMatching("JSON\\.parse", ["packages/app/src"])).toEqual(
      [...PARSES_JSON].sort(),
    );
  });

  it("the_app_reads_no_file", () => {
    const reads = filesMatching("readFileSync|readdirSync|readFile", [
      "packages/app/src",
    ]);

    expect(reads).toEqual([...READS_FILES].sort());

    const names = REMOVED_COMMANDS.join("|");

    expect(
      grep([
        "-nE",
        `"(${names})"`,
        "--",
        "packages/app/src",
        "packages/app/src-tauri/src",
        "packages/app/src-tauri/build.rs",
        "packages/app/src-tauri/permissions/app.toml",
        "packages/app/src-tauri/permissions/autogenerated",
      ]).filter(
        (line) => !line.startsWith("packages/app/src-tauri/src/lib.rs"),
      ),
    ).toEqual([]);

    expect(
      grep([
        "-nwE",
        names,
        "--",
        "packages/app/src-tauri/build.rs",
        "packages/app/src-tauri/permissions/app.toml",
        "packages/app/src-tauri/permissions/autogenerated",
      ]),
    ).toEqual([]);
  });

  it("the_app_runs_no_library_rule", () => {
    const names = LIBRARY_RULES.join("|");
    const hits = outsideTests(grep(["-lwE", names, "--", "packages/app/src"]));

    expect(hits).toEqual([]);
  });
});
